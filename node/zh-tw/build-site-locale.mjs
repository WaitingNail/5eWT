import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import {fileURLToPath} from "node:url";

const FILE = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(FILE), "../..");

export const PATH_SOURCE = path.join(ROOT, "translation/zh-TW/site/messages.json");
export const PATH_DATA = path.join(ROOT, "data/zh-TW/site.json");
export const PATH_DATA_JS = path.join(ROOT, "js/zh-tw/site-i18n-data.js");

const RE_STABLE_KEY = /^[a-z][A-Za-z0-9-]*(?:\.[a-z][A-Za-z0-9-]*)+$/;
const RE_PLACEHOLDER = /\{([A-Za-z][A-Za-z0-9_.-]*)\}/g;
const RE_HTML = /<\/?[a-z][^>]*>/gi;
const RE_UNSAFE_HTML = /<\s*script\b|\son[a-z]+\s*=|javascript\s*:/i;

function getPlaceholders (text) {
	return [...new Set([...text.matchAll(RE_PLACEHOLDER)].map(match => match[1]))].sort();
}

function getHtmlShape (text) {
	return [...text.matchAll(RE_HTML)]
		.map(match => {
			const tag = match[0];
			const name = /^<\/?\s*([a-z0-9-]+)/i.exec(tag)?.[1]?.toLowerCase();
			return `${/^<\//.test(tag) ? "/" : ""}${name}`;
		});
}

function assertEqualLists ({actual, expected, message}) {
	if (JSON.stringify(actual) === JSON.stringify(expected)) return;
	throw new Error(`${message}\n  English: ${JSON.stringify(expected)}\n  zh-TW:   ${JSON.stringify(actual)}`);
}

export function compileSiteLocale (source) {
	if (!source || typeof source !== "object" || Array.isArray(source)) throw new Error("Locale source must be an object.");
	if (!source._meta || typeof source._meta !== "object" || Array.isArray(source._meta)) throw new Error("Locale source is missing an object-valued _meta property.");
	if (source._meta.locale !== "zh-TW") throw new Error(`Expected locale \"zh-TW\"; got ${JSON.stringify(source._meta.locale)}.`);
	if (source._meta.fallbackLocale !== "en") throw new Error(`Expected fallbackLocale \"en\"; got ${JSON.stringify(source._meta.fallbackLocale)}.`);
	if (!source.messages || typeof source.messages !== "object" || Array.isArray(source.messages)) throw new Error("Locale source is missing an object-valued messages property.");

	const messages = {};
	const fallbacks = {};
	const english = {};
	const htmlKeys = [];
	const seenEnglish = new Map();

	Object.entries(source.messages)
		.sort(([keyA], [keyB]) => keyA < keyB ? -1 : keyA > keyB ? 1 : 0)
		.forEach(([key, entry]) => {
			if (!RE_STABLE_KEY.test(key)) throw new Error(`Invalid stable message key: ${JSON.stringify(key)}.`);
			if (!entry || typeof entry !== "object" || Array.isArray(entry)) throw new Error(`Message ${key} must be an object.`);

			const en = entry.en;
			const zhTw = entry["zh-TW"];
			if (typeof en !== "string" || !en.trim()) throw new Error(`Message ${key} has an empty or non-string English fallback.`);
			if (typeof zhTw !== "string" || !zhTw.trim()) throw new Error(`Message ${key} has an empty or non-string zh-TW translation.`);

			assertEqualLists({
				actual: getPlaceholders(zhTw),
				expected: getPlaceholders(en),
				message: `Message ${key} does not preserve interpolation placeholders.`,
			});

			const hasHtml = RE_HTML.test(en) || RE_HTML.test(zhTw);
			RE_HTML.lastIndex = 0;
			if (hasHtml && entry.isHtml !== true) throw new Error(`Message ${key} contains HTML but is not marked isHtml: true.`);
			if (entry.isHtml === true) {
				if (RE_UNSAFE_HTML.test(en) || RE_UNSAFE_HTML.test(zhTw)) throw new Error(`Message ${key} contains unsafe HTML.`);
				assertEqualLists({
					actual: getHtmlShape(zhTw),
					expected: getHtmlShape(en),
					message: `Message ${key} does not preserve its HTML element structure.`,
				});
				htmlKeys.push(key);
			}

			const duplicate = seenEnglish.get(en);
			if (duplicate && duplicate.zhTw !== zhTw) {
				throw new Error(`English alias ${JSON.stringify(en)} has conflicting translations in ${duplicate.key} and ${key}.`);
			}

			messages[key] = zhTw;
			fallbacks[key] = en;
			if (!duplicate) {
				english[en] = key;
				seenEnglish.set(en, {key, zhTw});
			}
		});

	return {
		_meta: {
			...source._meta,
			source: "translation/zh-TW/site/messages.json",
			generatedBy: "node/zh-tw/build-site-locale.mjs",
			messageCount: Object.keys(messages).length,
			englishAliasCount: Object.keys(english).length,
		},
		messages,
		english,
		fallbacks,
		htmlKeys,
	};
}

export async function buildSiteLocale () {
	const source = JSON.parse(await fs.readFile(PATH_SOURCE, "utf8"));
	const compiled = compileSiteLocale(source);
	const json = `${JSON.stringify(compiled, null, 2)}\n`;
	const js = [
		"/* This file is generated by node/zh-tw/build-site-locale.mjs. Do not edit directly. */",
		"\"use strict\";",
		"",
		`globalThis.SITE_I18N_ZH_TW_DATA = ${JSON.stringify(compiled, null, 2)};`,
		"",
	].join("\n");

	await Promise.all([
		fs.mkdir(path.dirname(PATH_DATA), {recursive: true}),
		fs.mkdir(path.dirname(PATH_DATA_JS), {recursive: true}),
	]);
	await Promise.all([
		fs.writeFile(PATH_DATA, json, "utf8"),
		fs.writeFile(PATH_DATA_JS, js, "utf8"),
	]);

	return compiled;
}

if (process.argv[1] && path.resolve(process.argv[1]) === FILE) {
	try {
		const compiled = await buildSiteLocale();
		console.log(`Built zh-TW site locale: ${compiled._meta.messageCount} messages, ${compiled._meta.englishAliasCount} English aliases.`);
	} catch (error) {
		console.error(error instanceof Error ? error.stack : error);
		process.exitCode = 1;
	}
}
